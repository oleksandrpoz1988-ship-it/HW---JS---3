
// Завдання 1: Перетворення масиву об’єктів у масив імен
const fruts = [
  { id: 0, name: "Apple" },
  { id: 1, name: "Tomat" },
  { id: 2, name: "Cherry" },
  { id: 3, name: "Orange" },
];

// Використовуємо метод .map(), щоб витягнути тільки поле 'name' з кожного об'єкта
const fruitNames = fruts.map(fruit => fruit.name);
console.log("Завдання 1 (Масив імен):", fruitNames);




// Завдання 2: Парні числа від 2 до 10
console.log("Завдання 2 (Парні числа):");
// Цикл починається з 2, виконується до 10 включно, збільшуючи i на 2 на кожному кроці
for (let i = 2; i <= 10; i += 2) {
  console.log(i);
}



// Завдання 3: Заміна "for" на "while"
console.log("Завдання 3 (Цикл while):");
let i = 0; // Початкове значення лічильника
while (i < 5) {
  console.log(`цифра ${i}!`); // Виправлено помилку з lpg на log
  i++; // Обов'язкове збільшення лічильника, щоб уникнути нескінченного циклу
}



// Завдання 4: Запит числа більше за 100
// Створюємо змінну для збереження введеного значення
let num;

// Цикл do...while спочатку виконує тіло циклу, а потім перевіряє умову
do {
  num = prompt("Введіть число, більше за 100", "");
} while (num <= 100 && num !== null && num !== ""); 
// Цикл повторюється, якщо введено число <= 100 І користувач не натиснув "Скасувати" чи не залишив пусте поле

console.log("Завдання 4 (Введене число):", num);


// Завдання 5: Обчислення середнього віку
const girls = [
  { age: 23, name: "Оля" },
  { age: 29, name: "Аня" },
  { age: 10, name: "Юля" },
  { age: 20, name: "Катя" },
];

let totalAge = 0; // Змінна для накопичення суми віку

// Проходимо по кожному об'єкту дівчини в масиві
for (let girl of girls) {
  totalAge += girl.age; // Додаємо вік до загальної суми
}

// Обчислюємо середній вік: загальна сума / кількість дівчат
const averageAge = totalAge / girls.length;

console.log("Завдання 5 (Середній вік):", averageAge);